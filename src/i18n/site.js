export function getDict(lang) {
  return DICT[lang] || DICT.ro
}

/** Picks a localized field off a category/item row, falling back to the RO base value. */
export function loc(entity, lang, field) {
  if (!entity) return ''
  if (!lang || lang === 'ro') return entity[field] || ''
  const t = entity.translations && entity.translations[lang]
  return (t && t[field]) || entity[field] || ''
}
