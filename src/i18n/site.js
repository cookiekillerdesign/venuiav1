function ruPlural(n, one, few, many) {
  const a = Math.abs(n) % 100, b = a % 10
  if (a > 10 && a < 20) return many
  if (b > 1 && b < 5) return few
  if (b === 1) return one
  return many
}
function roCount(n, sing, plur) { return n === 1 ? `1 ${sing}` : n % 100 >= 20 || n % 100 === 0 ? `${n} de ${plur}` : `${n} ${plur}` }

